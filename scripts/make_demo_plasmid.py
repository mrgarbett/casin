#!/usr/bin/env python3
"""Generate the SYNTHETIC demo plasmid in samples/ (GenBank and .dna).

Every base here comes from a seeded pseudo-random generator plus short
designed motifs (restriction sites, a start/stop codon frame). It is NOT a
real plasmid and none of its elements are biologically functional; the
feature names only exist to exercise the viewer.

    python3 scripts/make_demo_plasmid.py [outdir]
"""
import datetime
import os
import struct
import sys
from xml.sax.saxutils import escape, quoteattr

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "samples")
NAME = "pOC-demo"
DESCRIPTION = "SYNTHETIC demo plasmid for Restricto. Not a real construct; generated by scripts/make_demo_plasmid.py."

STOPS = {"TAA", "TAG", "TGA"}
COMP = str.maketrans("ACGT", "TGCA")


def revcomp(s):
    return s.translate(COMP)[::-1]


class Rng:
    """Small deterministic LCG so the output never changes between Python versions."""

    def __init__(self, seed):
        self.state = seed

    def next(self):
        self.state = (self.state * 6364136223846793005 + 1442695040888963407) % (1 << 64)
        return self.state >> 33

    def bases(self, n, gc=0.5):
        out = []
        for _ in range(n):
            r = self.next() % 1000
            if r < gc * 500:
                out.append("G")
            elif r < gc * 1000:
                out.append("C")
            elif r < gc * 1000 + (1 - gc) * 500:
                out.append("A")
            else:
                out.append("T")
        return "".join(out)

    def orf(self, codons):
        out = ["ATG"]
        while len(out) < codons:
            c = self.bases(3, 0.52)
            if c not in STOPS:
                out.append(c)
        out.append("TAA")
        return "".join(out)


rng = Rng(20261027)
parts = []      # (sequence, feature or None)
features = []   # dicts with start (0-based), end, strand, type, name, quals


def add(seq, ftype=None, name=None, strand=1, quals=None):
    start = sum(len(p) for p in parts)
    parts.append(seq)
    if ftype:
        features.append(dict(start=start, end=start + len(seq), strand=strand, type=ftype,
                             name=name, quals=quals or []))
    return start


# A NotI site split across the origin: the last 4 bases + the first 4.
NOTI = "GCGGCCGC"
add(NOTI[4:])
add(rng.bases(90))
add(rng.bases(48, 0.4), "promoter", "P-demo (synthetic)")
add(rng.bases(14))
add("AGGAGG", "RBS", "RBS-demo")
add(rng.bases(7))
orf_a = rng.orf(240)
add(orf_a, "CDS", "demoA", quals=[("codon_start", "1"), ("product", "synthetic demo protein A"),
                                 ("note", "random open reading frame, not a real gene")])
add(rng.bases(20))
add(rng.bases(40, 0.65), "terminator", "T-demo")
add(rng.bases(60))
# Multiple cloning site built from common 6-cutter sites.
mcs = "GAATTC" "GAGCTC" "GGTACC" "CCCGGG" "GGATCC" "TCTAGA" "GTCGAC" "CTGCAG" "GCATGC" "AAGCTT"
add(mcs, "misc_feature", "MCS")
add(rng.bases(80))
# Golden Gate style cassette: BsaI sites facing inward.
add("GGTCTC" + "A" + rng.bases(4) + rng.bases(120) + rng.bases(4) + "T" + "GAGACC",
    "misc_feature", "BsaI cassette")
add(rng.bases(70))
orf_r = rng.orf(180)
add(revcomp(orf_r), "CDS", "demoR", strand=-1, quals=[("codon_start", "1"), ("product", "synthetic demo protein R")])
add(rng.bases(60))
add(rng.bases(300, 0.55), "rep_origin", "ori-demo")
add(rng.bases(50))
# A split CDS (two exons) to exercise join() locations.
exon_orf = rng.orf(90)
exon1, exon2 = exon_orf[:150], exon_orf[150:]
e1 = add(exon1)
intron = "GT" + rng.bases(76) + "AG"
add(intron)
e2 = add(exon2)
features.append(dict(start=e1, end=e2 + len(exon2), strand=1, type="CDS", name="demoJ (split)",
                     segments=[(e1, e1 + len(exon1)), (e2, e2 + len(exon2))],
                     quals=[("codon_start", "1"), ("product", "synthetic two-exon demo")]))
add(rng.bases(90))
add(rng.bases(24), "primer_bind", "seq-fwd site")
add(rng.bases(400, 0.45))
add(NOTI[:4])

seq = "".join(parts)
n = len(seq)

# A feature that spans the origin (last 30 bp + first 40 bp).
features.append(dict(start=n - 30, end=n + 40, strand=0, type="misc_feature", name="origin tag", quals=[]))

primers = [
    ("seq-fwd", features[[f["name"] for f in features].index("seq-fwd site")]["start"], 24, 0),
]
mcs_start = seq.index(mcs)
primers.append(("mcs-rev", mcs_start + len(mcs) + 10, 20, 1))


def segments(f):
    if "segments" in f:
        return f["segments"]
    if f["end"] > n:
        return [(f["start"], n), (0, f["end"] - n)]
    return [(f["start"], f["end"])]


def gb_location(f):
    parts_ = ["%d..%d" % (a + 1, b) for a, b in segments(f)]
    loc = parts_[0] if len(parts_) == 1 else "join(%s)" % ",".join(parts_)
    return "complement(%s)" % loc if f["strand"] == -1 else loc


def translate(s):
    code = "FFLLSSSSYY**CC*WLLLLPPPPHHQQRRRRIIIMTTTTNNKKSSRRVVVVAAAADDEEGGGG"
    idx = {"T": 0, "C": 1, "A": 2, "G": 3}
    return "".join(code[idx[s[i]] * 16 + idx[s[i + 1]] * 4 + idx[s[i + 2]]] for i in range(0, len(s) - 2, 3))


def feature_bases(f):
    s = "".join(seq[a:b] if b <= n else seq[a:] + seq[:b - n] for a, b in segments(f))
    return revcomp(s) if f["strand"] == -1 else s


def wrap_qualifier(text, width=59):
    lines = []
    while len(text) > width:
        cut = text.rfind(" ", 0, width + 1)
        if cut <= 0:
            lines.append(text[:width]); text = text[width:]
        else:
            lines.append(text[:cut]); text = text[cut + 1:]
    lines.append(text)
    return lines


def write_genbank(path):
    date = datetime.date(2026, 10, 27).strftime("%d-%b-%Y").upper()
    out = ["LOCUS       %-16s %11d bp    DNA     circular SYN %s" % (NAME, n, date)]
    out.append("DEFINITION  " + "\n            ".join(wrap_qualifier(DESCRIPTION, 68)))
    out += ["ACCESSION   .", "VERSION     .", "KEYWORDS    synthetic; demo.",
            "SOURCE      synthetic DNA construct", "  ORGANISM  synthetic DNA construct",
            "FEATURES             Location/Qualifiers",
            "     source          1..%d" % n,
            '                     /mol_type="other DNA"',
            '                     /organism="synthetic DNA construct"']
    for f in features:
        out.append("     %-15s %s" % (f["type"], gb_location(f)))
        quals = [("label", f["name"])] + list(f["quals"])
        if f["type"] == "CDS":
            quals.append(("translation", translate(feature_bases(f)).rstrip("*")))
        for k, v in quals:
            if k == "codon_start":
                out.append("                     /%s=%s" % (k, v))
                continue
            text = '/%s="%s"' % (k, v)
            if k == "translation":
                lines = [text[i:i + 59] for i in range(0, len(text), 59)]
            else:
                lines = wrap_qualifier(text)
            out += ["                     " + l for l in lines]
    out.append("ORIGIN")
    low = seq.lower()
    for i in range(0, n, 60):
        out.append("%9d %s" % (i + 1, " ".join(low[j:j + 10] for j in range(i, min(i + 60, n), 10))))
    out.append("//")
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")


def packet(kind, payload):
    return struct.pack(">BI", kind, len(payload)) + payload


COLORS = {"CDS": "#62a0ea", "promoter": "#57e389", "terminator": "#f66151", "rep_origin": "#f8e45c",
          "RBS": "#cdab8f", "misc_feature": "#c0bfbc", "primer_bind": "#c061cb"}


def write_dna(path):
    feats = []
    for i, f in enumerate(features):
        segs = []
        segs_ = segments(f)
        if f["end"] > n:   # one wrapping segment, as SnapGene stores it
            segs_ = [(f["start"], f["end"] - n)]
        for j, (a, b) in enumerate(segs_):
            if j > 0:
                pa, pb = segs_[j - 1]
                segs.append('<Segment range="%d-%d" type="gap"/>' % (pb + 1, a))
            segs.append('<Segment range="%d-%d" color="%s" type="standard"/>'
                        % (a + 1, b, COLORS.get(f["type"], "#c0bfbc")))
        qs = []
        for k, v in f["quals"]:
            if k == "codon_start":
                qs.append('<Q name="codon_start"><V int="%s"/></Q>' % v)
            else:
                qs.append('<Q name="%s"><V text=%s/></Q>' % (k, quoteattr("<html><body>%s</body></html>" % escape(v))))
        direction = {1: "1", -1: "2", 0: "0"}[f["strand"]]
        feats.append('<Feature recentID="%d" name=%s directionality="%s" type="%s">%s%s</Feature>'
                     % (i, quoteattr(f["name"]), direction, f["type"], "".join(segs), "".join(qs)))
    features_xml = '<?xml version="1.0"?><Features nextValidID="%d">%s</Features>' % (len(features), "".join(feats))

    prs = []
    for name, start, length, strand in primers:
        site = seq[start:start + length]
        bases = revcomp(site) if strand == 1 else site
        prs.append('<Primer name="%s" sequence="%s"><BindingSite location="%d-%d" boundStrand="%d"/></Primer>'
                   % (name, bases.lower(), start, start + length - 1, strand))
    primers_xml = '<?xml version="1.0"?><Primers>%s</Primers>' % "".join(prs)

    notes_xml = ('<Notes><Description>%s</Description><Synthetic>1</Synthetic></Notes>'
                 % escape("<html><body>%s</body></html>" % DESCRIPTION))

    data = packet(0x09, b"SnapGene" + struct.pack(">HHH", 1, 15, 19))
    data += packet(0x00, bytes([0x01]) + seq.encode())
    data += packet(0x0A, features_xml.encode())
    data += packet(0x05, primers_xml.encode())
    data += packet(0x06, notes_xml.encode())
    data += packet(0x63, b"ignored")   # an unknown packet type, which readers must skip
    with open(path, "wb") as fh:
        fh.write(data)


os.makedirs(OUT, exist_ok=True)
write_genbank(os.path.join(OUT, "pOC-demo.gb"))
write_dna(os.path.join(OUT, "pOC-demo.dna"))
print("wrote %d bp, %d features to %s" % (n, len(features), os.path.abspath(OUT)))
