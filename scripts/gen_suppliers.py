#!/usr/bin/env python3
"""Generate src/core/suppliers.cpp: which commercial suppliers sell each of
our enzymes, from REBASE (via Biopython's Bio.Restriction, generated from
REBASE's emboss_s export). Usage:

    python3 scripts/gen_suppliers.py > src/core/suppliers.cpp
"""
import pathlib
import re

from Bio.Restriction.Restriction_Dictionary import rest_dict, suppliers

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "src/core/enzymes.cpp").read_text()
names = re.findall(r'\{"(\w+)", "[A-Z]+", -?\d+, -?\d+', src)

print("""// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by scripts/gen_suppliers.py from REBASE (http://rebase.neb.com)
// supplier data. Do not edit by hand.
#include "enzymes.h"

#include <map>

namespace oc {

const std::vector<Supplier> &suppliers()
{
    static const std::vector<Supplier> list = {""")
for code in sorted(suppliers):
    print(f'        {{\'{code}\', "{suppliers[code][0]}"}},')
print("""    };
    return list;
}

std::string enzymeSuppliers(const std::string &name)
{
    static const std::map<std::string, std::string> codes = {""")
for name in names:
    s = "".join(sorted(rest_dict.get(name, {}).get("suppl", ())))
    print(f'        {{"{name}", "{s}"}},')
print("""    };
    auto it = codes.find(name);
    return it == codes.end() ? std::string() : it->second;
}

} // namespace oc""")
